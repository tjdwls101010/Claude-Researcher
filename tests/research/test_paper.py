TEMPLATE = Path(__file__).with_name("fixtures") / "template"
NOW = "2026-09-07T01:00:00Z"


@pytest.fixture
def lay(tmp_path):
    lay = project.init_project(tmp_path, "toy", question="q", now=NOW)
